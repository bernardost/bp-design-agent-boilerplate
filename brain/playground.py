def piece_html(p: dict) -> str:
    facts = []
    if MULTI_PROJECT and p["project"]:
        facts.append(html.escape(PROJECT_LABEL.get(p["project"], p["project"])))
    if p["source"]:
        facts.append("from " + html.escape(p["source"]))
    if p["exploration"]:
        facts.append("exploration " + html.escape(p["exploration"]))
    if p["decision"]:
        facts.append("decision " + html.escape(p["decision"]))
    if p["shipped_note"]:
        facts.append("shipped " + html.escape(p["shipped_note"]))
    if not p["has_record"]:
        facts.append('<span class="warn">no piece.md</span>')
    if p["unlogged"]:
        facts.append(f'<span class="warn">{", ".join(p["unlogged"])} not in the version log</span>')
    rows = []
    for v in reversed(p["versions"]):
        cls = " final" if v["file"] == p["final_file"] else ""
        rows.append(f'<li class="{cls.strip()}"><a href="{p["slug"]}/{v["file"]}">{html.escape(v["label"])}</a>'
                    f'<span class="date">{html.escape(v["date"])}</span>'
                    f'<span class="note">{html.escape(v["note"])}</span></li>')
    for s in p["shipped"]:
        rows.append(f'<li class="shipped"><a href="{p["slug"]}/{s}">{html.escape(s[:-5])}</a>'
                    f'<span class="date"></span><span class="note">the HTML counterpart of what went live</span></li>')
    versions = f'<ul class="versions">{"".join(rows)}</ul>' if rows else '<p class="empty">no versions yet</p>'
    return f"""<div class="piece" id="{html.escape(p["slug"])}">
  <div>
    <div class="status" data-s="{html.escape(p["status"])}">{html.escape(p["status"])}</div>
    <h3>{html.escape(p["title"])}</h3>
    {f'<p class="brief">{html.escape(p["brief"])}</p>' if p["brief"] else ""}
    <div class="facts">{" · ".join(facts)}</div>
  </div>
  {versions}
</div>"""


def spreads_html() -> str:
    pages = sorted((BRAIN / "explorations").glob("*.html"), reverse=True)
    if not pages:
        return ""
    items = []
    for pg in pages:
        m = re.match(r"(\d{4}-\d{2}-\d{2})-(.+)", pg.stem)
        date, name = (m.group(1), m.group(2).replace("-", " ")) if m else ("", pg.stem)
        items.append(f'<li><span class="date">{date}</span><a href="../explorations/{pg.name}">{html.escape(name)}</a></li>')
    return (f'<div class="panel"><div class="kicker">Explorations · the spreads, one click away</div>'
            f'<ul class="spreads">{"".join(items)}</ul></div>')


def build(ps: list[dict]) -> str:
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M")
    if MULTI_PROJECT:
        groups: dict = {}
        for p in ps:
            groups.setdefault(p["project"] or "—", []).append(p)
        body = "".join(
            f'<div class="panel"><div class="kicker">{html.escape(PROJECT_LABEL.get(k, k))}</div>'
            + "".join(piece_html(p) for p in v) + "</div>" for k, v in groups.items())
    else:
        body = "".join(piece_html(p) for p in ps)
    if not ps:
        body = ('<p class="empty">No pieces yet. <code>/playground</code> starts one from a design or '
                'from nothing; <code>/prototype</code> builds a first pass here.</p>')
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Playground — {html.escape(PROJECT_NAME)}</title>
{FONT_LINK}<style>{CSS}{PAGE_CSS}</style></head><body>
<div class="wrap">
<div class="top">
  <div class="kicker">{html.escape(PROJECT_NAME)} · playground</div>
  <h1>Every piece, every version, nothing lost.</h1>
  <div class="meta">generated {stamp} from <code>brain/playground/*/piece.md</code> and the files
    beside them — regenerate with <code>python3 brain/playground.py</code></div>
</div>
{body}
{spreads_html()}
</div></body></html>"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--open", action="store_true")
    args = ap.parse_args()
    if not DIR.exists():
        print("no brain/playground/ — nothing to render")
        return 0
    ps = pieces()
    for p in ps:
        (DIR / p["slug"] / "versions.js").write_text(versions_js(p), encoding="utf-8")
    out = DIR / "index.html"
    out.write_text(build(ps), encoding="utf-8")
    n = sum(len(p["versions"]) for p in ps)
    print(f"{out.relative_to(ROOT)}  ·  {len(ps)} piece(s), {n} version(s)")
    for p in ps:
        flags = []
        if not p["has_record"]:
            flags.append("no piece.md")
        if p["unlogged"]:
            flags.append(f"{', '.join(p['unlogged'])} not in the version log")
        if flags:
            print(f"  {p['slug']}: " + "; ".join(flags))
    if args.open:
        subprocess.run(["open", str(out)], check=False)
    return 0


if __name__ == "__main__":
    sys.exit(main())
