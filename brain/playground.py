#!/usr/bin/env python3
"""playground.py — the index of every playground piece, and each piece's version strip.

    python3 brain/playground.py [--open]

`brain/playground/<slug>/` holds a piece: `piece.md` (the record) and `vNN-<name>.html` (the
versions, every one kept). This reads the folders and writes two projections:

  brain/playground/index.html          every piece, its status, its versions, plus the
                                       exploration spreads — one page to open first
  brain/playground/<slug>/versions.js  `window.PLAYGROUND` for that piece, which is what gives
                                       each version file its version strip in the bar

Both are regenerated from the files and never read back. Delete them and nothing is lost.
`render.py` runs this with the other projections; `/playground` runs it alone after writing a
version, so the strip knows about the file that was just made.

The record format is `brain/playground/README.md`. This parses the little it needs: the
frontmatter's `project:` and `status:`, the title line, `Brief:`, `Final:`, `Shipped:`, and the
`## Versions` list, matched to files by their `vNN` prefix.
"""

from __future__ import annotations

import argparse
import html
import json
import re
import subprocess
import sys
from datetime import datetime
from pathlib import Path

BRAIN = Path(__file__).resolve().parent
ROOT = BRAIN.parent
DIR = BRAIN / "playground"
RESERVED = {"_canvas", "_template"}
STATUSES = ("exploring", "current", "final", "shipped")
VERSION_FILE = re.compile(r"^(v\d{2,})(?:-([a-z0-9][a-z0-9-]*))?\.html$")

sys.path.insert(0, str(BRAIN))
from config import PROJECT_NAME, MULTI_PROJECT, PROJECT_LABEL  # noqa: E402
from feed import CSS, FONT_LINK  # noqa: E402


def frontmatter(text: str) -> dict:
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    out = {}
    if not m:
        return out
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            out[k.strip()] = v.split("#", 1)[0].strip()
    return out


def field(text: str, name: str) -> str:
    m = re.search(rf"^{name}:\s*(.+?)\s*$", text, re.M)
    v = m.group(1) if m else ""
    return "" if v.startswith("{{") else v


def parse(folder: Path) -> dict:
    """One piece: the record plus the files that exist beside it."""
    rec = folder / "piece.md"
    text = rec.read_text(encoding="utf-8") if rec.exists() else ""
    fm = frontmatter(text)
    title_m = re.search(r"^# (.+)$", text, re.M)
    notes = {}
    for m in re.finditer(r"^- (v\d{2,})\s*—\s*(\S+)?\s*—?\s*(.*)$", text, re.M):
        notes[m.group(1)] = (m.group(2) or "", m.group(3).strip())
    versions = []
    for f in sorted(folder.glob("*.html")):
        vm = VERSION_FILE.match(f.name)
        if vm:
            date, note = notes.get(vm.group(1), ("", ""))
            versions.append({"file": f.name, "v": vm.group(1),
                             "label": vm.group(1) + (" · " + vm.group(2).replace("-", " ") if vm.group(2) else ""),
                             "date": date, "note": note})
    shipped = sorted(f.name for f in folder.glob("shipped*.html"))
    final = field(text, "Final")
    final_file = next((v["file"] for v in versions if v["v"] == final or v["file"] == final), "")
    return {
        "slug": folder.name, "path": rec, "has_record": rec.exists(),
        "title": title_m.group(1).strip() if title_m else folder.name,
        "project": fm.get("project", ""), "status": fm.get("status", "") or "exploring",
        "source": fm.get("source", ""), "brief": field(text, "Brief"),
        "exploration": field(text, "Exploration"), "decision": field(text, "Decision"),
        "final": final, "final_file": final_file, "shipped_note": field(text, "Shipped"),
        "versions": versions, "shipped": shipped,
        "unlogged": [v["v"] for v in versions if v["v"] not in notes],
    }


def pieces() -> list[dict]:
    if not DIR.exists():
        return []
    return [parse(p) for p in sorted(DIR.iterdir())
            if p.is_dir() and p.name not in RESERVED and not p.name.startswith(".")]


def versions_js(p: dict) -> str:
    data = {"slug": p["slug"], "title": p["title"], "status": p["status"],
            "versions": p["versions"] + [{"file": s, "v": "shipped", "label": "shipped", "date": "", "note": ""} for s in p["shipped"]],
            "final": p["final_file"]}
    return ("// generated by brain/playground.py from piece.md and the files beside it — do not edit\n"
            f"window.PLAYGROUND = {json.dumps(data, ensure_ascii=False)};\n")


